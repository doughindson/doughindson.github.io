// Generate src/styles/tokens.css from tools/figma-tokens.json (the Figma variables).
// Desktop values are the default; the Mobile mode applies at max-width: 767px (the site's breakpoint).
import fs from 'fs';

const t = JSON.parse(fs.readFileSync('tools/figma-tokens.json', 'utf8'));
const slug = (s) => s.replace(/\//g, '-');
const px = (n) => `${+n.toFixed(2)}px`;
const desktop = [];
const mobile = [];

for (const [k, v] of Object.entries(t.color)) desktop.push(`--color-${slug(k)}: ${v};`);
for (const [k, v] of Object.entries(t.space)) { desktop.push(`--space-${k}: ${px(v[0])};`); }
for (const [k, [d, m]] of Object.entries(t.layout)) {
  desktop.push(`--${slug(k)}: ${px(d)};`);
  if (d !== m) mobile.push(`--${slug(k)}: ${px(m)};`);
}
for (const [k, v] of Object.entries(t.radius)) desktop.push(`--radius-${k}: ${v}px;`);
desktop.push(`--font-base: '${t.type['family/base']}', system-ui, sans-serif;`);
for (const [k, v] of Object.entries(t.type)) {
  if (typeof v === 'string') continue;
  const n = slug(k);
  const [sd, sm] = v.size, [ld, lm] = v['line-height'], [ed, em] = v['letter-spacing'];
  desktop.push(`--type-${n}-size: ${px(sd)};`, `--type-${n}-line-height: ${px(ld)};`, `--type-${n}-letter-spacing: ${ed / 100}em;`);
  mobile.push(`--type-${n}-size: ${px(sm)};`, `--type-${n}-line-height: ${px(lm)};`);
  if (ed !== em) mobile.push(`--type-${n}-letter-spacing: ${em / 100}em;`);
}

const css = `/* GENERATED by tools/build-css.mjs from tools/figma-tokens.json — do not edit by hand. */
:root {
  ${desktop.join('\n  ')}
}

@media (max-width: 767px) {
  :root {
    ${mobile.join('\n    ')}
  }
}
`;
fs.mkdirSync('src/styles', { recursive: true });
fs.writeFileSync('src/styles/tokens.css', css);
console.log('wrote src/styles/tokens.css', desktop.length, 'desktop /', mobile.length, 'mobile');
