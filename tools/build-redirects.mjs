// Generate public/_redirects (Cloudflare Pages) from inventory.json: every old Squarespace path -> its new URL.
import fs from 'fs';

const { pages } = JSON.parse(fs.readFileSync('inventory.json', 'utf8'));
const rules = new Map();
const add = (from, to) => { if (from !== to) rules.set(from, to); };

for (const p of pages) {
  const path = p.path;
  if (p.type === 'project') add(path, path.replace('/design-motion/', '/projects/'));
  else if (p.type === 'project-index') add(path, '/projects');
  else if (p.type === 'legacy') add(path, '/projects'); // old portfolio: content saved in /content, no pages built
  else if (p.slug === 'home-alias') add(path, '/');
  else if (p.slug === '404') add(path, '/');
  // '/' and '/about' keep their URLs
}
const body = [...rules].map(([f, t]) => `${f} ${t} 301`).join('\n');
fs.writeFileSync('public/_redirects', `# GENERATED by tools/build-redirects.mjs from inventory.json\n${body}\n`);
